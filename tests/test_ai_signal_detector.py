from collections.abc import Mapping

import pytest

from pr_radar.contracts import (
    ChangedFileMetadata,
    CommitMetadata,
    EvidenceReference,
    LOW_CONFIDENCE_TAG,
    PrEvidencePack,
    PrInput,
    PrMetadata,
    RawEvidence,
)
from pr_radar.detectors.ai_signal import detect_ai_signals


def _pr_input() -> PrInput:
    return PrInput(
        provider="github",
        deployment="github_self_hosted",
        repository="arkdevelopers/code-review-agent",
        pull_request_number=59,
        url="https://git.linecorp.com/arkdevelopers/code-review-agent/pull/59",
    )


def _evidence_pack(
    *,
    pr_metadata: PrMetadata | None = None,
    commits: tuple[CommitMetadata, ...] = (),
    changed_files: tuple[ChangedFileMetadata, ...] = (),
    file_contents: Mapping[str, str] | None = None,
) -> PrEvidencePack:
    return PrEvidencePack(
        pr_input=_pr_input(),
        pr_metadata=pr_metadata
        or PrMetadata(
            title="Update review helper",
            body="",
            author_login="alice",
            head_ref="feature/review-helper",
            base_ref="main",
        ),
        commits=commits,
        changed_files=changed_files,
        raw_evidence=RawEvidence(
            diff="diff --git a/src/review.py b/src/review.py",
            file_contents=file_contents or {},
        ),
        evidence_refs=(
            EvidenceReference(kind="diff", ref="diff:pull"),
        ),
    )


def test_detect_ai_signals_flags_bot_authors_and_committers() -> None:
    """Catches detectors that ignore commit actor evidence."""
    evidence_pack = _evidence_pack(
        commits=(
            CommitMetadata(
                sha="abc1234",
                author_login="devin[bot]",
                committer_login="github-actions[bot]",
                message="Generate review helper",
            ),
        ),
    )

    findings = detect_ai_signals(evidence_pack)

    bot_findings = [
        finding for finding in findings if finding.signal_type == "bot_actor"
    ]
    assert len(bot_findings) == 1
    assert bot_findings[0].strength == "strong"
    assert bot_findings[0].status == "warning"
    assert bot_findings[0].score >= 80
    assert bot_findings[0].confidence >= 0.8
    assert bot_findings[0].decision_source == "deterministic"
    assert bot_findings[0].evidence_refs == (
        EvidenceReference(kind="commit", ref="commit:abc1234"),
    )


