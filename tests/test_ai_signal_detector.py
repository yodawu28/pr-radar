@pytest.mark.parametrize(
    "signature_text",
    [
        "Generated with Claude Code.",
        "Generated by Codex.",
    ],
)
def test_detect_ai_signals_flags_pr_body_signatures_with_redacted_excerpt(
    signature_text: str,
) -> None:
    """Catches detectors that ignore explicit generated-by signatures."""
    evidence_pack = _evidence_pack(
        pr_metadata=PrMetadata(
            title="Update review helper",
            body=(
                f"{signature_text}\n"
                "api_key=sk_live_1234567890abcdef must never appear in reports."
            ),
            author_login="alice",
            head_ref="feature/review-helper",
            base_ref="main",
        ),
    )

    findings = detect_ai_signals(evidence_pack)

    signature_findings = [
        finding for finding in findings if finding.signal_type == "pr_signature"
    ]
    assert len(signature_findings) == 1
    assert signature_findings[0].strength == "strong"
    assert signature_findings[0].status == "warning"
    assert signature_findings[0].score >= 85
    assert signature_findings[0].confidence >= 0.85
    assert signature_findings[0].decision_source == "deterministic"
    assert signature_findings[0].evidence_refs == (
        EvidenceReference(kind="pr", ref="body:signature"),
    )
    assert signature_findings[0].redacted_excerpts
    rendered_excerpts = "\n".join(
        excerpt.text for excerpt in signature_findings[0].redacted_excerpts
    )
    assert signature_text in rendered_excerpts
    assert "sk_live_1234567890abcdef" not in rendered_excerpts


def test_detect_ai_signals_keeps_repo_markers_weak_and_visible() -> None:
    """Catches detectors that treat repo marker files as definitive proof."""
    evidence_pack = _evidence_pack(
        file_contents={
            ".agents/skills/reviewer.md": "Review agent instructions.",
            "AGENTS.md": "Repository agent operating guide.",
            "CLAUDE.md": "Claude operating notes.",
        },
    )

    findings = detect_ai_signals(evidence_pack)

    assert findings
    assert {finding.signal_type for finding in findings} == {"repo_marker"}
    assert {finding.strength for finding in findings} == {"weak"}
    assert {finding.status for finding in findings} == {"info"}
    assert all(finding.score <= 40 for finding in findings)
    assert all(finding.confidence <= 0.4 for finding in findings)
    assert all(finding.decision_source == "deterministic" for finding in findings)
    assert all(finding.tags == (LOW_CONFIDENCE_TAG,) for finding in findings)
    assert {
        evidence_ref
        for finding in findings
        for evidence_ref in finding.evidence_refs
    } == {
        EvidenceReference(kind="repo_file", ref="file:.agents/skills/reviewer.md"),
        EvidenceReference(kind="repo_file", ref="file:AGENTS.md"),
        EvidenceReference(kind="repo_file", ref="file:CLAUDE.md"),
    }


def test_detect_ai_signals_records_calibration_reasons_for_each_signal_kind() -> None:
    """Catches unexplained score/confidence values in AI signal findings."""
    evidence_pack = _evidence_pack(
        pr_metadata=PrMetadata(
            title="Update review helper",
            body="Generated by Codex.",
            author_login="alice",
            head_ref="agent/review-helper",
            base_ref="main",
        ),
        commits=(
            CommitMetadata(
                sha="abc1234",
                author_login="devin[bot]",
                committer_login="alice",
                message="Generate review helper",
            ),
        ),
        file_contents={
            "AGENTS.md": "Repository agent operating guide.",
        },
    )

    findings = detect_ai_signals(evidence_pack)

    calibration_by_type = {
        finding.signal_type: {
            "status": finding.status,
            "score": finding.score,
            "confidence": finding.confidence,
            "decision_source": finding.decision_source,
            "tags": finding.tags,
            "calibration_reason": finding.calibration_reason,
        }
        for finding in findings
    }
    assert calibration_by_type == {
        "bot_actor": {
            "status": "warning",
            "score": 90,
            "confidence": 0.9,
            "decision_source": "deterministic",
            "tags": (),
            "calibration_reason": "bot_identity_strong_ai_assistance_signal",
        },
        "branch_prefix": {
            "status": "warning",
            "score": 70,
            "confidence": 0.7,
            "decision_source": "deterministic",
            "tags": (),
            "calibration_reason": "agent_branch_prefix_medium_ai_assistance_signal",
        },
        "pr_signature": {
            "status": "warning",
            "score": 95,
            "confidence": 0.95,
            "decision_source": "deterministic",
            "tags": (),
            "calibration_reason": "explicit_pr_body_signature_strong_ai_assistance_signal",
        },
        "repo_marker": {
            "status": "info",
            "score": 35,
            "confidence": 0.35,
            "decision_source": "deterministic",
            "tags": (LOW_CONFIDENCE_TAG,),
            "calibration_reason": "repo_marker_weak_project_level_signal",
        },
    }
