from collections.abc import Mapping
from urllib.error import URLError

from typer.testing import CliRunner

import pr_radar.cli as cli
from pr_radar.contracts import (
    CommitMetadata,
    FetchFailure,
    PrEvidencePack,
    PrInput,
    PrMetadata,
    RawEvidence,
    Report,
)
from pr_radar.github_adapter import GitHubEvidenceFetchError


def test_scan_baseline_no_fetch_mode_stays_parser_only(monkeypatch) -> None:
    """Catches baseline scan accidentally requiring repository fetch access."""

    def fail_if_called(*args, **kwargs):
        raise AssertionError("baseline scan must not fetch PR evidence")

    monkeypatch.setattr(
        "pr_radar.application.scan.fetch_pr_evidence",
        fail_if_called,
    )

    result = CliRunner().invoke(
        cli.app,
        ["scan", "https://git.example.internal/team/repo/pull/42"],
    )

    assert result.exit_code == 0
    assert "PR Radar Local Report" in result.output
    assert "PR: team/repo#42" in result.output
    assert "No AI-generation evidence collected yet." in result.output


def test_scan_fetch_enabled_renders_mocked_evidence_ai_signal_report(
    monkeypatch,
) -> None:
    """Catches scan commands that accept fetch mode but ignore fetched evidence."""

    def fake_fetch_pr_evidence(
        pr_input: PrInput,
        *,
        env: Mapping[str, str],
        http_get,
        include_file_contents: bool = False,
    ) -> PrEvidencePack:
        return PrEvidencePack(
            pr_input=pr_input,
            pr_metadata=PrMetadata(
                title="Add generated review helper",
                body="Generated by Codex.\napi_key=sk_live_1234567890abcdef",
                author_login="alice",
                head_ref="agent/review-helper",
                base_ref="main",
            ),
            commits=(
                CommitMetadata(
                    sha="abc1234",
                    author_login="devin[bot]",
                    committer_login="alice",
                    message="Generate review helper",
                ),
            ),
            raw_evidence=RawEvidence(
                diff="diff --git a/src/review.py b/src/review.py\n+TOKEN=secret",
                file_contents={"AGENTS.md": "Repository agent operating guide."},
            ),
        )

    monkeypatch.setattr(
        "pr_radar.application.scan.fetch_pr_evidence",
        fake_fetch_pr_evidence,
    )

    result = CliRunner().invoke(
        cli.app,
        [
            "scan",
            "https://git.linecorp.com/arkdevelopers/code-review-agent/pull/59",
            "--fetch-evidence",
        ],
    )

    assert result.exit_code == 0
    assert "PR Radar Local Report" in result.output
    assert "PR: arkdevelopers/code-review-agent#59" in result.output
    assert "AI Signal: 4 signal(s) detected" in result.output
    assert "bot_actor" in result.output
    assert "branch_prefix" in result.output
    assert "pr_signature" in result.output
    assert "repo_marker" in result.output
    assert "Evidence: commit:abc1234" in result.output
    assert "Evidence: head_ref:agent/review-helper" in result.output
    assert "Evidence: body:signature" in result.output
    assert "Excerpt: Generated by Codex." in result.output
    assert "api_key=<REDACTED_SECRET>" in result.output
    assert "TOKEN=secret" not in result.output
    assert "diff --git" not in result.output
    assert "sk_live_1234567890abcdef" not in result.output


def test_scan_fetch_enabled_fails_closed_without_leaking_fetch_error_content(
    monkeypatch,
) -> None:
    """Catches fetch/auth failures leaking raw tokens or raw diff bodies."""

    def fake_fetch_pr_evidence(
        pr_input: PrInput,
        *,
        env: Mapping[str, str],
        http_get,
        include_file_contents: bool = False,
    ) -> PrEvidencePack:
        raise GitHubEvidenceFetchError(
            FetchFailure(
                reason="missing_token",
                message=(
                    "Missing token ghp_raw_secret while reading "
                    "diff --git a/src/secret.py b/src/secret.py"
                ),
            ),
        )

    monkeypatch.setattr(
        "pr_radar.application.scan.fetch_pr_evidence",
        fake_fetch_pr_evidence,
    )

    result = CliRunner().invoke(
        cli.app,
        [
            "scan",
            "https://git.linecorp.com/arkdevelopers/code-review-agent/pull/59",
            "--fetch-evidence",
        ],
    )

    assert result.exit_code == 1
    assert "Unable to fetch PR evidence" in result.output
    assert "missing_token" in result.output
    assert "ghp_raw_secret" not in result.output
    assert "diff --git" not in result.output
    assert "Traceback" not in result.output


def test_scan_fetch_enabled_transport_errors_fail_closed_without_traceback(
    monkeypatch,
) -> None:
    """Catches raw transport exceptions escaping the CLI fetch boundary."""

    def fail_transport(*args, **kwargs):
        raise URLError("dns failure using ghp_raw_secret")

    monkeypatch.setenv("GHE_TOKEN", "ghp_raw_secret")
    monkeypatch.setattr("pr_radar.adapters.github.urllib_http.urlopen", fail_transport)

    result = CliRunner().invoke(
        cli.app,
        [
            "scan",
            "https://git.linecorp.com/arkdevelopers/code-review-agent/pull/59",
            "--fetch-evidence",
        ],
    )

    assert result.exit_code == 1
    assert "Unable to fetch PR evidence" in result.output
    assert "timeout" in result.output
    assert "ghp_raw_secret" not in result.output
    assert "Traceback" not in result.output


def test_scan_fetch_enabled_accepts_local_workspace_path_option(
    monkeypatch,
    tmp_path,
) -> None:
    """Catches CLI adapters that cannot request source-present blast radius."""
    captured: dict[str, object] = {}

    def fake_scan_pr(
        pr_url: str,
        *,
        fetch_evidence: bool = False,
        local_workspace_path=None,
    ) -> Report:
        captured["pr_url"] = pr_url
        captured["fetch_evidence"] = fetch_evidence
        captured["local_workspace_path"] = local_workspace_path
        return Report(
            overall_status="safe",
            pr_input=PrInput(
                provider="github",
                deployment="github_com",
                repository="example/repo",
                pull_request_number=17,
                url=pr_url,
            ),
            ai_signal_summary="No AI-generation evidence detected.",
        )

    monkeypatch.setattr(cli, "scan_pr", fake_scan_pr)

    result = CliRunner().invoke(
        cli.app,
        [
            "scan",
            "https://github.com/example/repo/pull/17",
            "--fetch-evidence",
            "--local-workspace-path",
            str(tmp_path),
        ],
    )

    assert result.exit_code == 0
    assert captured == {
        "pr_url": "https://github.com/example/repo/pull/17",
        "fetch_evidence": True,
        "local_workspace_path": tmp_path,
    }
