from collections.abc import Mapping

from pr_radar.contracts import (
    ChangedFileMetadata,
    CommitMetadata,
    PrEvidencePack,
    PrInput,
    PrMetadata,
    RawEvidence,
)
from pr_radar.report_renderer import render_text_report
from pr_radar.scan import scan_pr


def _changed_file(path: str, diff: str) -> ChangedFileMetadata:
    return ChangedFileMetadata(
        path=path,
        status="modified",
        additions=diff.count("\n+"),
        deletions=diff.count("\n-"),
    )


def test_scan_pr_fetch_mode_builds_evidence_backed_report(monkeypatch) -> None:
    """Catches domain scan orchestration leaking back into the CLI adapter."""

    def fake_fetch_pr_evidence(
        pr_input: PrInput,
        *,
        env: Mapping[str, str],
        http_get,
        include_file_contents: bool = False,
    ) -> PrEvidencePack:
        return PrEvidencePack(
            pr_input=pr_input,
            pr_metadata=PrMetadata(
                title="Add generated review helper",
                body="Generated by Codex.",
                author_login="alice",
                head_ref="agent/review-helper",
                base_ref="main",
            ),
            commits=(
                CommitMetadata(
                    sha="abc1234",
                    author_login="devin[bot]",
                    committer_login="alice",
                    message="Generate review helper",
                ),
            ),
            raw_evidence=RawEvidence(
                diff="diff --git a/src/review.py b/src/review.py",
                file_contents={"AGENTS.md": "Repository agent operating guide."},
            ),
        )

    monkeypatch.setattr(
        "pr_radar.application.scan.fetch_pr_evidence",
        fake_fetch_pr_evidence,
    )

    report = scan_pr(
        "https://git.linecorp.com/arkdevelopers/code-review-agent/pull/59",
        fetch_evidence=True,
        env={"GHE_TOKEN": "ghe_unit_secret_value"},
        http_get=lambda url, *, headers: None,
    )

    assert report.overall_status == "needs_attention"
    assert report.pr_input.repository == "arkdevelopers/code-review-agent"
    assert "4 signal(s) detected" in report.ai_signal_summary
    assert "Evidence: commit:abc1234" in report.ai_signal_summary
    assert "Evidence: body:signature" in report.ai_signal_summary


def test_scan_pr_fetch_mode_integrates_static_findings_and_context_metadata(
    monkeypatch,
) -> None:
    """Catches fetched-evidence scans that collect evidence but skip risk detectors."""
    dependency_diff = (
        "diff --git a/pyproject.toml b/pyproject.toml\n"
        "@@ [project] dependencies @@\n"
        '+    "requests>=2.32",\n'
    )
    migration_diff = (
        "diff --git a/db/migrations/20261026090100_rewrite_orders.sql "
        "b/db/migrations/20261026090100_rewrite_orders.sql\n"
        "@@ high impact migration @@\n"
        "+ALTER TABLE orders ALTER COLUMN status SET NOT NULL;\n"
    )
    disabled_test_diff = (
        "diff --git a/tests/test_payments.py b/tests/test_payments.py\n"
        "@@ retry limit tests @@\n"
        '+@pytest.mark.skip(reason="flaky api_key=sk_live_1234567890abcdef")\n'
        "+def test_charge_retry_limit_is_enforced():\n"
        "+    assert charge(request) == expected_receipt\n"
    )

    def fake_fetch_pr_evidence(
        pr_input: PrInput,
        *,
        env: Mapping[str, str],
        http_get,
        include_file_contents: bool = False,
    ) -> PrEvidencePack:
        return PrEvidencePack(
            pr_input=pr_input,
            pr_metadata=PrMetadata(
                title="Update static-risk surfaces",
                body="",
                author_login="alice",
                head_ref="feature/static-risk",
                base_ref="main",
            ),
            changed_files=(
                _changed_file("pyproject.toml", dependency_diff),
                _changed_file(
                    "db/migrations/20261026090100_rewrite_orders.sql",
                    migration_diff,
                ),
                _changed_file("tests/test_payments.py", disabled_test_diff),
            ),
            raw_evidence=RawEvidence(
                diff=dependency_diff + migration_diff + disabled_test_diff,
                file_contents={
                    "pyproject.toml": (
                        "[project]\n"
                        "dependencies = [\n"
                        '    "requests>=2.32",\n'
                        "]\n"
                    ),
                    "db/migrations/20261026090100_rewrite_orders.sql": (
                        "ALTER TABLE orders ALTER COLUMN status SET NOT NULL;\n"
                    ),
                    "tests/test_payments.py": (
                        '@pytest.mark.skip(reason="flaky '
                        'api_key=sk_live_1234567890abcdef")\n'
                        "PRIVATE_RAW_SOURCE\n"
                    ),
                },
            ),
        )

    monkeypatch.setattr(
        "pr_radar.application.scan.fetch_pr_evidence",
        fake_fetch_pr_evidence,
    )

    report = scan_pr(
        "https://github.com/example/repo/pull/17",
        fetch_evidence=True,
        env={"GITHUB_TOKEN": "github_unit_secret_value"},
        http_get=lambda url, *, headers: None,
    )

    finding_ids = {finding.id for finding in report.findings}
    assert finding_ids == {
        "dependency.added.pyproject",
        "migration.ambiguous.high_impact_schema_change",
        "test_shape.disabled_test",
    }
    assert report.overall_status == "needs_attention"
    assert {finding.id for finding in report.low_confidence_findings} == {
        "migration.ambiguous.high_impact_schema_change",
    }
    assert report.evaluation_metadata["context_grade"] == "review_grade"
    assert report.evaluation_metadata["context_envelope"] == "available"
    assert report.evaluation_metadata["context_finding_count"] == "3"
    assert int(report.evaluation_metadata["context_budget_used_chars"]) > 0
    assert int(report.evaluation_metadata["context_budget_max_chars"]) >= int(
        report.evaluation_metadata["context_budget_used_chars"],
    )

    rendered = render_text_report(report)
    serialized_report = str(report.model_dump(mode="json"))
    report_text = f"{rendered}\n{serialized_report}"
    assert "dependency.added.pyproject" in rendered
    assert "migration.ambiguous.high_impact_schema_change" in rendered
    assert "test_shape.disabled_test" in rendered
    assert "api_key=<REDACTED_SECRET>" in serialized_report
    assert "sk_live_1234567890abcdef" not in report_text
    assert "PRIVATE_RAW_SOURCE" not in report_text
    assert "diff --git" not in report_text
