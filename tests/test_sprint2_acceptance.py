from collections.abc import Mapping

import pytest

from pr_radar.github_adapter import GitHubHttpResponse
from pr_radar.report_renderer import render_text_report
from pr_radar.scan import scan_pr


DIFF_ACCEPT = "application/vnd.github.v3.diff"
PUBLIC_REPOSITORY = "octo-org/pr-radar-demo"
PUBLIC_PR_NUMBER = 7
PUBLIC_PR_API_URL = (
    f"https://api.github.com/repos/{PUBLIC_REPOSITORY}/pulls/{PUBLIC_PR_NUMBER}"
)
SELF_HOSTED_REPOSITORY = "arkdevelopers/code-review-agent"
SELF_HOSTED_PR_NUMBER = 59
SELF_HOSTED_PR_API_URL = (
    "https://git.linecorp.com/api/v3/repos/"
    f"{SELF_HOSTED_REPOSITORY}/pulls/{SELF_HOSTED_PR_NUMBER}"
)


class FakeGitHubHttp:
    def __init__(
        self,
        routes: Mapping[str | tuple[str, str | None], GitHubHttpResponse],
    ) -> None:
        self.routes = dict(routes)
        self.calls: list[dict[str, object]] = []

    def get(
        self,
        url: str,
        *,
        headers: Mapping[str, str],
    ) -> GitHubHttpResponse:
        self.calls.append({"url": url, "headers": dict(headers)})
        route_key = (url, headers.get("Accept"))
        response = self.routes.get(route_key, self.routes.get(url))
        if response is None:
            raise AssertionError(f"unexpected HTTP GET {url}")
        return response


def test_github_com_pr_url_fetch_smoke_renders_review_grade_report() -> None:
    """Catches GitHub.com review smoke tests that cannot fetch file evidence."""
    token = "gh_unit_secret_value"
    raw_url = (
        "https://raw.githubusercontent.com/"
        f"{PUBLIC_REPOSITORY}/main/AGENTS.md"
    )
    fake_http = FakeGitHubHttp(
        _review_grade_routes(
            api_pr_url=PUBLIC_PR_API_URL,
            raw_url=raw_url,
        ),
    )

    report = scan_pr(
        f"https://github.com/{PUBLIC_REPOSITORY}/pull/{PUBLIC_PR_NUMBER}",
        fetch_evidence=True,
        env={"GITHUB_TOKEN": token},
        http_get=fake_http.get,
    )
    rendered = render_text_report(report)

    assert report.overall_status == "needs_attention"
    assert f"PR: {PUBLIC_REPOSITORY}#{PUBLIC_PR_NUMBER}" in rendered
    assert "AI Signal: 4 signal(s) detected" in rendered
    assert "Evidence: commit:abc1234" in rendered
    assert "Evidence: file:AGENTS.md" in rendered
    assert "Excerpt: Generated by Codex." in rendered
    assert "api_key=<REDACTED_SECRET>" in rendered
    assert "sk_live_1234567890abcdef" not in rendered
    assert "TOKEN=secret" not in rendered
    assert _called(fake_http, raw_url)


@pytest.mark.parametrize(
    ("pr_url", "api_pr_url", "token_env_var", "token"),
    [
        (
            f"https://git.linecorp.com/{SELF_HOSTED_REPOSITORY}/pull/"
            f"{SELF_HOSTED_PR_NUMBER}",
            SELF_HOSTED_PR_API_URL,
            "GHE_TOKEN",
            "ghe_unit_secret_value",
        ),
    ],
)
def test_self_hosted_pr_url_fetch_smoke_renders_review_grade_report(
    pr_url: str,
    api_pr_url: str,
    token_env_var: str,
    token: str,
) -> None:
    """Catches self-hosted PR URL review drifting away from safe local fetch."""
    raw_url = "https://git.linecorp.com/raw/AGENTS.md"
    fake_http = FakeGitHubHttp(
        _review_grade_routes(
            api_pr_url=api_pr_url,
            raw_url=raw_url,
        ),
    )

    report = scan_pr(
        pr_url,
        fetch_evidence=True,
        env={token_env_var: token},
        http_get=fake_http.get,
    )
    rendered = render_text_report(report)

    assert report.overall_status == "needs_attention"
    assert f"Bearer {token}" in _authorization_headers(fake_http)
    assert "AI Signal: 4 signal(s) detected" in rendered
    assert "Evidence: head_ref:agent/review-helper" in rendered
    assert "Evidence: body:signature" in rendered
    assert "Evidence: file:AGENTS.md" in rendered
    assert "api_key=<REDACTED_SECRET>" in rendered
    assert token not in rendered
    assert "TOKEN=secret" not in rendered
    assert _called(fake_http, raw_url)


def _review_grade_routes(
    *,
    api_pr_url: str,
    raw_url: str,
) -> Mapping[str | tuple[str, str | None], GitHubHttpResponse]:
    return {
        api_pr_url: _response(
            {
                "title": "Add generated review helper",
                "body": "Generated by Codex.\napi_key=sk_live_1234567890abcdef",
                "user": {"login": "alice"},
                "head": {"ref": "agent/review-helper"},
                "base": {"ref": "main"},
                "labels": [{"name": "agent-pr"}],
            },
        ),
        f"{api_pr_url}/commits": _response(
            [
                {
                    "sha": "abc1234",
                    "author": {"login": "devin[bot]"},
                    "committer": {"login": "alice"},
                    "commit": {"message": "Generate review helper"},
                },
            ],
        ),
        f"{api_pr_url}/files": _response(
            [
                {
                    "filename": "AGENTS.md",
                    "status": "modified",
                    "additions": 8,
                    "deletions": 1,
                    "raw_url": raw_url,
                },
            ],
        ),
        (api_pr_url, DIFF_ACCEPT): _response(
            "diff --git a/AGENTS.md b/AGENTS.md\n+TOKEN=secret",
        ),
        raw_url: _response("Repository agent operating guide."),
    }


def _response(body: object) -> GitHubHttpResponse:
    return GitHubHttpResponse(status_code=200, body=body)


def _called(fake_http: FakeGitHubHttp, url: str) -> bool:
    return any(call["url"] == url for call in fake_http.calls)


def _authorization_headers(fake_http: FakeGitHubHttp) -> str:
    values = []
    for call in fake_http.calls:
        headers = call["headers"]
        if isinstance(headers, Mapping):
            authorization = headers.get("Authorization")
            if isinstance(authorization, str):
                values.append(authorization)
    return "\n".join(values)
