from importlib import import_module, util

import pytest

from pr_radar.contracts import (
    ChangedFileMetadata,
    EvidenceReference,
    Finding,
    PrEvidencePack,
    PrInput,
    PrMetadata,
    RawEvidence,
    RedactedExcerpt,
)
from pr_radar.scan import scan_pr


def _static_risk_module():
    assert util.find_spec("pr_radar.detectors.static_risk") is not None, (
        "expected pr_radar.detectors.static_risk to provide the shared "
        "static-risk detector harness"
    )
    return import_module("pr_radar.detectors.static_risk")


def _evidence_pack() -> PrEvidencePack:
    return PrEvidencePack(
        pr_input=PrInput(
            provider="github",
            deployment="github_com",
            repository="example/repo",
            pull_request_number=17,
            url="https://github.com/example/repo/pull/17",
        ),
        pr_metadata=PrMetadata(
            title="Add risky dependency",
            body="Generated by Codex.",
            author_login="alice",
            head_ref="agent/dependency",
            base_ref="main",
        ),
        changed_files=(
            ChangedFileMetadata(
                path="pyproject.toml",
                status="modified",
                additions=1,
                deletions=0,
            ),
        ),
        raw_evidence=RawEvidence(
            diff=(
                "diff --git a/pyproject.toml b/pyproject.toml\n"
                '+ requests = "999.0.0"\n'
                "+ api_key=sk_live_1234567890abcdef\n"
            ),
            file_contents={
                "pyproject.toml": (
                    '[project]\ndependencies = ["requests==999.0.0"]\n'
                    "PRIVATE_RAW_SOURCE"
                ),
            },
        ),
    )


def _report_safe_dependency_detector(
    evidence_pack: PrEvidencePack,
) -> tuple[Finding, ...]:
    assert evidence_pack.changed_files[0].path == "pyproject.toml"
    return (
        Finding(
            id="dependency.added.requests",
            pillar="security_supply_chain",
            title="New dependency requires supply-chain review",
            status="warning",
            score=68,
            confidence=0.74,
            evidence_refs=("file:pyproject.toml", "diff:pyproject.toml"),
            decision_source="deterministic",
            tags=("detector:dependency",),
        ),
    )


def test_static_detector_harness_runs_detectors_and_builds_context() -> None:
    """Locks the shared detector orchestration boundary for S3 detector families."""
    static_risk = _static_risk_module()

    result = static_risk.run_static_detectors(
        _evidence_pack(),
        detectors=(_report_safe_dependency_detector,),
        context_max_chars=2_000,
    )

    assert result.findings[0].id == "dependency.added.requests"
    assert result.context_envelope.context_grade == "review_grade"
    assert result.context_envelope.items[0].finding_id == "dependency.added.requests"
    assert result.context_envelope.items[0].detector_id == "dependency"

    serialized = str(result.model_dump())
    assert "sk_live_1234567890abcdef" not in serialized
    assert "PRIVATE_RAW_SOURCE" not in serialized
    assert "diff --git" not in serialized


def test_static_detector_harness_rejects_unstable_finding_ids() -> None:
    """Prevents prose titles or ad hoc IDs from becoming evaluation keys."""
    static_risk = _static_risk_module()

    def unstable_id_detector(_: PrEvidencePack) -> tuple[Finding, ...]:
        return (
            Finding(
                id="New Dependency Added",
                pillar="security_supply_chain",
                title="New dependency requires supply-chain review",
                status="warning",
                score=68,
                confidence=0.74,
                evidence_refs=("file:pyproject.toml",),
                decision_source="deterministic",
            ),
        )

    with pytest.raises(static_risk.DetectorContractError, match="stable finding id"):
        static_risk.run_static_detectors(
            _evidence_pack(),
            detectors=(unstable_id_detector,),
            context_max_chars=2_000,
        )


