def test_static_detector_harness_accepts_safe_redacted_excerpts() -> None:
    """Allows report-safe excerpts that intentionally quote non-sensitive code."""
    static_risk = _static_risk_module()
    safe_excerpt = '+ assert charge(request) == expected_receipt'
    evidence_pack = PrEvidencePack(
        pr_input=PrInput(
            provider="github",
            deployment="github_com",
            repository="example/repo",
            pull_request_number=17,
            url="https://github.com/example/repo/pull/17",
        ),
        pr_metadata=PrMetadata(
            title="Add payment tests",
            body="",
            author_login="alice",
            head_ref="agent/payment-tests",
            base_ref="main",
        ),
        changed_files=(
            ChangedFileMetadata(
                path="tests/test_payments.py",
                status="modified",
                additions=1,
                deletions=0,
            ),
        ),
        raw_evidence=RawEvidence(
            diff=(
                "diff --git a/tests/test_payments.py b/tests/test_payments.py\n"
                f"{safe_excerpt}\n"
            ),
            file_contents={"tests/test_payments.py": safe_excerpt},
        ),
    )

    def detector(_: PrEvidencePack) -> tuple[Finding, ...]:
        return (
            Finding(
                id="test_shape.example",
                pillar="test_integrity",
                title="Example test excerpt",
                status="warning",
                score=60,
                confidence=0.6,
                evidence_refs=("file:tests/test_payments.py",),
                decision_source="deterministic",
                redacted_excerpts=(
                    RedactedExcerpt(
                        evidence_ref=EvidenceReference(
                            kind="diff",
                            ref="diff:tests/test_payments.py",
                        ),
                        text=safe_excerpt,
                    ),
                ),
            ),
        )

    result = static_risk.run_static_detectors(
        evidence_pack,
        detectors=(detector,),
        context_max_chars=2_000,
    )

    assert result.context_envelope.items[0].redacted_excerpts == (safe_excerpt,)


